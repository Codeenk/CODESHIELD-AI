"""Render a scan as JSON, SARIF 2.1.0, HTML, or PDF."""
from __future__ import annotations

import html as html_lib
import io
from typing import Any

from .. import __version__
from ..schemas import Scan

_SARIF_LEVEL = {
    "critical": "error",
    "high": "error",
    "medium": "warning",
    "low": "note",
    "info": "note",
}


def to_json(scan: Scan) -> str:
    return scan.model_dump_json(indent=2)


def to_sarif(scan: Scan) -> dict[str, Any]:
    """Emit SARIF 2.1.0 compatible with GitHub code scanning."""
    rules: dict[str, dict] = {}
    results: list[dict] = []
    for finding in scan.findings:
        if finding.cwe not in rules:
            rules[finding.cwe] = {
                "id": finding.cwe,
                "name": finding.cwe.replace("-", ""),
                "shortDescription": {"text": finding.cwe_title or finding.cwe},
                "helpUri": f"https://cwe.mitre.org/data/definitions/{finding.cwe.split('-')[-1]}.html"
                if finding.cwe.startswith("CWE-") and finding.cwe.split("-")[-1].isdigit()
                else "https://owasp.org/Top10/",
                "properties": {"owasp": finding.owasp, "severity": finding.severity},
            }
        results.append(
            {
                "ruleId": finding.cwe,
                "level": _SARIF_LEVEL.get(finding.severity, "warning"),
                "message": {"text": f"{finding.message} (engine={finding.engine}, confidence={finding.confidence:.0%})"},
                "locations": [
                    {
                        "physicalLocation": {
                            "artifactLocation": {"uri": finding.path},
                            "region": {"startLine": finding.start_line, "endLine": finding.end_line},
                        }
                    }
                ],
                "properties": {
                    "function": finding.function,
                    "fingerprint": finding.fingerprint,
                    "knowledgeRef": finding.knowledge_ref,
                },
            }
        )
    return {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [
            {
                "tool": {
                    "driver": {
                        "name": "CodeShield AI",
                        "version": __version__,
                        "informationUri": "https://github.com/",
                        "rules": list(rules.values()),
                    }
                },
                "results": results,
            }
        ],
    }


