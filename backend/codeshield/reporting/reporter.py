def to_html(scan: Scan) -> str:
    sev_cards = "".join(
        f'<div class="card"><b class="sev-{sev}">{scan.summary.by_severity.get(sev, 0)}</b>'
        f'<span class="muted">{sev}</span></div>'
        for sev in ("critical", "high", "medium", "low")
    )
    blocks = []
    for f in scan.findings:
        evidence = "".join(
            f"<pre><code>{html_lib.escape(e.snippet)}</code></pre>" for e in f.evidence[:4]
        )
        explanation = ""
        if f.explanation:
            explanation = f'<p class="muted">{html_lib.escape(f.explanation.get("why", ""))}</p>'
        blocks.append(
            f'<div class="finding"><h3 class="sev-{f.severity}">{html_lib.escape(f.cwe_title or f.cwe)} '
            f'<span class="tag">{f.cwe}</span><span class="tag">{f.severity}</span>'
            f'<span class="tag">{f.engine}</span><span class="tag">{f.confidence:.0%}</span></h3>'
            f'<div class="muted"><code>{html_lib.escape(f.path)}</code> :: '
            f'<code>{html_lib.escape(f.function)}</code> L{f.start_line}–{f.end_line}</div>'
            f"<p>{html_lib.escape(f.message)}</p>{explanation}{evidence}</div>"
        )
    return _HTML.format(
        scan_id=scan.id, target=html_lib.escape(scan.target),
        created=scan.created_at.strftime("%Y-%m-%d %H:%M UTC"),
        total=scan.summary.total_findings, sev_cards=sev_cards,
        files=scan.summary.files_scanned, model="yes" if scan.summary.model_used else "no",
        findings_html="\n".join(blocks) or '<p class="muted">No findings. 🎉</p>',
        version=__version__,
    )


def to_pdf(scan: Scan) -> bytes:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

    styles = getSampleStyleSheet()
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, topMargin=18 * mm, bottomMargin=18 * mm)
    story: list = [
        Paragraph(f"CodeShield AI — Security Report", styles["Title"]),
        Paragraph(
            f"Scan {scan.id} · target {html_lib.escape(scan.target)} · "
            f"{scan.created_at.strftime('%Y-%m-%d %H:%M UTC')}",
            styles["Normal"],
        ),
        Spacer(1, 8),
        Paragraph(
            f"<b>{scan.summary.total_findings}</b> findings across "
            f"<b>{scan.summary.files_scanned}</b> files. "
            f"Model used: {'yes' if scan.summary.model_used else 'rules-only'}.",
            styles["Normal"],
        ),
        Spacer(1, 10),
    ]
    for f in scan.findings:
        story.append(
            Paragraph(
                f'<b><font color="#c0392b">{html_lib.escape(f.cwe_title or f.cwe)}</font></b> '
                f'[{f.cwe} · {f.severity} · {f.engine} · {f.confidence:.0%}]',
                styles["Heading3"],
            )
        )
        story.append(
            Paragraph(
                f"<code>{html_lib.escape(f.path)} :: {html_lib.escape(f.function)} "
                f"L{f.start_line}-{f.end_line}</code>",
                styles["Normal"],
            )
        )
        story.append(Paragraph(html_lib.escape(f.message), styles["Normal"]))
        if f.explanation:
            story.append(Paragraph(html_lib.escape(f.explanation.get("remediation", "")), styles["Italic"]))
        for ev in f.evidence[:3]:
            story.append(Paragraph(f"<code>{html_lib.escape(ev.snippet)}</code>", styles["Code"]))
        story.append(Spacer(1, 8))
    doc.build(story)
    return buffer.getvalue()
