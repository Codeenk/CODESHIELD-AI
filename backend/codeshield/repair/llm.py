"""Optional LLM repair through an OpenAI-compatible endpoint or a local HF model."""
from __future__ import annotations

import json
import re
import textwrap
from typing import Any, Optional

import httpx

from .. import config
from ..schemas import CodeUnit, Finding
from .templates import TemplateFix, unified_diff

_SYSTEM = (
    "You are a senior application security engineer. Repair exactly one vulnerability in the "
    "provided function. Preserve the public signature, observable behavior, language, and "
    "framing. Do not add placeholders or TODO comments. Do not introduce new dependencies when "
    "the standard library is sufficient. Return JSON only, with this shape: "
    '{"fixes":[{"source":"<complete corrected function>","summary":"<one line>",'
    '"rationale":"<why it is safe>","semantic_risk":true|false}]}'
)


def available() -> bool:
    return bool(config.LLM_BASE_URL or config.REPAIR_MODEL_ID)


def _prompt(finding: Finding, unit: CodeUnit) -> str:
    remediation = (finding.explanation or {}).get("remediation") or []
    return (
        f"Language: {unit.language}\n"
        f"CWE: {finding.cwe} {finding.cwe_title}\n"
        f"Evidence: {finding.evidence[0].reason if finding.evidence else finding.message}\n"
        f"Guidance: {' '.join(remediation)}\n"
        f"File: {finding.path}\n"
        f"Code:\n```{unit.language}\n{unit.source}\n```\n"
        "Return up to three independent fixes as JSON. Each source must be the complete "
        "corrected function, not a diff."
    )


def _escape_control_chars(text: str) -> str:
    """Escape raw newlines/tabs that local models emit inside JSON strings."""
    out: list[str] = []
    in_string = False
    escaped = False
    for char in text:
        if in_string:
            if escaped:
                out.append(char)
                escaped = False
            elif char == "\\":
                out.append(char)
                escaped = True
            elif char == '"':
                out.append(char)
                in_string = False
            elif char == "\n":
                out.append("\\n")
            elif char == "\r":
                out.append("\\r")
            elif char == "\t":
                out.append("\\t")
            else:
                out.append(char)
        else:
            if char == '"':
                in_string = True
            out.append(char)
    return "".join(out)


def _normalize_triple_quotes(text: str) -> str:
    """Convert Python-style triple-quoted JSON values into valid JSON strings."""
    return re.sub(r'"""(.*?)"""', lambda match: json.dumps(match.group(1)), text, flags=re.S)


def _parse_json(text: str) -> Optional[Any]:
    normalized = _normalize_triple_quotes(text)
    candidates = [text, normalized, _escape_control_chars(normalized), _escape_control_chars(text)]
    for candidate in candidates:
        try:
            return json.loads(candidate)
        except ValueError:
            pass
        for opener, closer in (("[", "]"), ("{", "}")):
            start = candidate.find(opener)
            end = candidate.rfind(closer)
            if start < 0 or end <= start:
                continue
            snippet = candidate[start:end + 1]
            for attempt in (snippet, re.sub(r",\s*([}\]])", r"\1", snippet)):
                try:
                    return json.loads(attempt)
                except ValueError:
                    continue
    return None


def _extract_json(text: str) -> Optional[Any]:
    cleaned = text.strip()
    cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned)
    cleaned = re.sub(r"\s*```$", "", cleaned)
    return _parse_json(cleaned)


def _from_payload(payload: Any, finding: Finding, unit: CodeUnit) -> list[TemplateFix]:
    if isinstance(payload, dict):
        fixes = payload.get("fixes") or []
    elif isinstance(payload, list):
        fixes = payload
    else:
        fixes = []
    results: list[TemplateFix] = []
    for fix in fixes[: config.REPAIR_MAX_CANDIDATES]:
        if not isinstance(fix, dict):
            continue
        source = textwrap.dedent(str(fix.get("source") or "")).strip()
        if not source or source == unit.source.strip():
            continue
        if unit.language == "python":
            try:
                import ast
                ast.parse(source)
            except SyntaxError:
                continue
        source = source.rstrip("\n") + "\n"
        results.append(
            TemplateFix(
                source=source,
                summary=str(fix.get("summary") or "LLM-generated repair")[:240],
                rationale=str(fix.get("rationale") or "Generated by the configured repair model.")[:800],
                semantic_risk=bool(fix.get("semantic_risk", True)),
                generator="llm",
            )
        )
    return results


def _remote(finding: Finding, unit: CodeUnit, count: int) -> list[TemplateFix]:
    url = config.LLM_BASE_URL.rstrip("/")
    if not url.endswith("/chat/completions"):
        url += "/chat/completions"
    headers = {"Content-Type": "application/json"}
    if config.LLM_API_KEY:
        headers["Authorization"] = f"Bearer {config.LLM_API_KEY}"
    body = {
        "model": config.LLM_MODEL,
        "temperature": config.LLM_TEMPERATURE,
        "max_tokens": config.LLM_MAX_TOKENS,
        "n": max(1, min(count, 3)),
        "messages": [
            {"role": "system", "content": _SYSTEM},
            {"role": "user", "content": _prompt(finding, unit)},
        ],
    }
    with httpx.Client(timeout=config.LLM_TIMEOUT) as client:
        response = client.post(url, headers=headers, json=body)
        response.raise_for_status()
        data = response.json()
    results: list[TemplateFix] = []
    for choice in data.get("choices", [])[:count]:
        content = choice.get("message", {}).get("content", "")
        payload = _extract_json(content)
        if payload:
            results.extend(_from_payload(payload, finding, unit))
    return results


def _local(finding: Finding, unit: CodeUnit, count: int) -> list[TemplateFix]:
    from transformers import pipeline

    generator = pipeline(
        "text-generation", model=config.REPAIR_MODEL_ID, device_map="auto",
        torch_dtype="auto",
    )
    prompt = f"<|im_start|>system\n{_SYSTEM}<|im_end|>\n<|im_start|>user\n{_prompt(finding, unit)}<|im_end|>\n<|im_start|>assistant\n"
    outputs = generator(
        prompt, max_new_tokens=config.LLM_MAX_TOKENS, num_return_sequences=max(1, count),
        do_sample=True, temperature=max(0.05, config.LLM_TEMPERATURE), return_full_text=False,
    )
    results: list[TemplateFix] = []
    for output in outputs:
        payload = _extract_json(output.get("generated_text", ""))
        if payload:
            results.extend(_from_payload(payload, finding, unit))
    return results


def generate(finding: Finding, unit: CodeUnit, count: int = 2) -> list[TemplateFix]:
    if not available():
        return []
    try:
        if config.LLM_BASE_URL:
            fixes = _remote(finding, unit, count)
        else:
            fixes = _local(finding, unit, count)
    except Exception:
        return []
    unique: dict[str, TemplateFix] = {}
    for fix in fixes:
        unique.setdefault(fix.source, fix)
    return list(unique.values())[:count]
